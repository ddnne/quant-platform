_PY_ENCODE_ARG_NAME: dict[str, str] = {
    "return": "return_value",
}
_PY_ENCODE_SKIP_FIELDS: frozenset[str] = frozenset({"version", "candidate"})
_PY_ENCODE_REQUIRED_ARGS: frozenset[str] = frozenset(
    {"n_expected", "n_cells", "n_complete"}
)


def _py_schema_prop_type(name: str, spec: Mapping[str, Any] | bool) -> str:
    """Python annotation for one schema property. Not a grade policy."""
    if spec is True:
        return "object"
    if not isinstance(spec, Mapping):
        raise ValueError(f"Evaluation IR schema property {name!r} must be an object")
    if name == "candidate" and "const" in spec:
        raise ValueError("Evaluation IR types must not const-bind candidate")
    if "const" in spec:
        const = spec["const"]
        if isinstance(const, str):
            return f"Literal[{json.dumps(const)}]"
        if const is None:
            return "None"
        if isinstance(const, bool):
            return f"Literal[{const}]"
        if isinstance(const, (int, float)) and not isinstance(const, bool):
            return f"Literal[{const!r}]"
        raise ValueError(
            f"Evaluation IR schema property {name!r} unsupported const {const!r}"
        )
    declared = spec.get("type")
    if declared is None:
        return "object"
    names = (declared,) if isinstance(declared, str) else tuple(declared)
    mapping = {
        "string": "str",
        "boolean": "bool",
        "integer": "int",
        "number": "float",
        "null": "None",
        "object": "Mapping[str, object]",
        "array": "list[object]",
    }
    parts: list[str] = []
    for type_name in names:
        mapped = mapping.get(str(type_name))
        if mapped is None:
            raise ValueError(
                f"Evaluation IR schema property {name!r} unsupported type {type_name!r}"
            )
        parts.append(mapped)
    return " | ".join(parts)


