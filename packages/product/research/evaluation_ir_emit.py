def evaluation_ir_types_py_source(*, root: Path | None = None) -> str:
    """Emit Python TypedDicts from schema.json properties. Not a grade policy."""
    schema = _load_schema(root=root)
    properties = schema["properties"]
    if not isinstance(properties, Mapping) or not properties:
        raise ValueError("Evaluation IR schema properties must be a non-empty object")
    version = properties["version"]["const"]
    if not isinstance(version, str) or not version:
        raise ValueError("Evaluation IR schema version const must be a string")
    required = schema.get("required")
    if not isinstance(required, list) or any(not isinstance(x, str) for x in required):
        raise ValueError("Evaluation IR schema required must be a list of strings")
    required_set = set(required)
    payload_lines: list[str] = []
    encode_lines: list[str] = []
    for name, spec in properties.items():
        py_type = _py_schema_prop_type(name, spec)
        payload_type = py_type if name in required_set else f"NotRequired[{py_type}]"
        payload_lines.append(f"        {json.dumps(name)}: {payload_type},")
        if name in _PY_ENCODE_SKIP_FIELDS:
            continue
        arg_name = _PY_ENCODE_ARG_NAME.get(name, name)
        encode_type = (
            py_type if name in _PY_ENCODE_REQUIRED_ARGS else f"NotRequired[{py_type}]"
        )
        encode_lines.append(f"        {json.dumps(arg_name)}: {encode_type},")
    missing_encode = [name for name in _PY_ENCODE_REQUIRED_ARGS if name not in properties]
    extra_skip = sorted(_PY_ENCODE_SKIP_FIELDS - set(properties))
    extra_rename = sorted(set(_PY_ENCODE_ARG_NAME) - set(properties))
    if missing_encode or extra_skip or extra_rename:
        raise ValueError(
            "Python encode arg maps must equal schema.json properties: "
            f"missing_required={missing_encode} extra_skip={extra_skip} "
            f"extra_rename={extra_rename}"
        )
    typing_names = ["TypedDict"]
    joined = "\n".join(payload_lines + encode_lines)
    if "Literal[" in joined:
        typing_names.insert(0, "Literal")
    if "Mapping[" in joined:
        typing_names.insert(typing_names.index("TypedDict"), "Mapping")
    if "NotRequired[" in joined:
        typing_names.insert(typing_names.index("TypedDict"), "NotRequired")
    imports = ", ".join(typing_names)
    payload_body = "\n".join(payload_lines)
    encode_body = "\n".join(encode_lines)
    return (
        '"""Generated by research.evaluation_ir from specs/evaluation_ir/schema.json. '
        "Do not edit by hand.\n"
        "\n"
        "Property types from schema.json. Grade is job_candidate_grade only; this "
        "module is not a grade policy.\n"
        "TypedDict cannot ban unknown fields (additionalProperties: false); runtime "
        "validate_evaluation_ir_schema remains SoT.\n"
        f"version const {version}.\n"
        '"""\n'
        "from __future__ import annotations\n"
        "\n"
        f"from typing import {imports}\n"
        "\n"
        "EvaluationIRPayload = TypedDict(\n"
        '    "EvaluationIRPayload",\n'
        "    {\n"
        f"{payload_body}\n"
        "    },\n"
        "    total=True,\n"
        ")\n"
        "\n"
        "EvaluationIREncodeArgs = TypedDict(\n"
        '    "EvaluationIREncodeArgs",\n'
        "    {\n"
        f"{encode_body}\n"
        "    },\n"
        "    total=True,\n"
        ")\n"
    )


